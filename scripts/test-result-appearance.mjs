import {build} from 'esbuild';
import vm from 'node:vm';
import assert from 'node:assert/strict';
const bundle=await build({entryPoints:['apps/extension/src/result-appearance.ts'],bundle:true,write:false,platform:'node',format:'cjs'});
const module={exports:{}};
vm.runInNewContext(bundle.outputFiles[0].text,{module,exports:module.exports,Intl,Date});
const {resultAppearance}=module.exports;
const today=new Intl.DateTimeFormat('sv-SE',{timeZone:'Europe/Istanbul',year:'numeric',month:'2-digit',day:'2-digit'}).format(new Date());
const base={status:'UNCERTAIN',asOf:new Date().toISOString(),indices:[{indexCode:'XKTUM',isMember:true,period:today}],sources:[{sourceName:'Borsa İstanbul',url:'https://borsaistanbul.com/datum/hisse_endeks_katilim_ds.csv'}]};
assert.equal(resultAppearance(base).variant,'success');
assert.equal(resultAppearance({...base,status:'NON_COMPLIANT'}).variant,'danger');
assert.equal(resultAppearance({...base,status:'COMPLIANT'}).variant,'success');
for(const status of ['INSUFFICIENT_DATA','STALE_DATA','CONFLICTING_SOURCES']) assert.equal(resultAppearance({...base,status}).variant,'warning');
assert.equal(resultAppearance({...base,sources:[]}).variant,'warning');
assert.equal(resultAppearance({...base,asOf:''}).variant,'warning');
assert.equal(resultAppearance({...base,asOf:'2020-01-01T00:00:00Z'}).variant,'warning');
assert.equal(resultAppearance({...base,indices:[{indexCode:'XKTUM',isMember:false,period:today}]}).variant,'warning');
assert.equal(resultAppearance({...base,indices:[{indexCode:'XKTUM',isMember:true,period:'2099-01-01'}]}).variant,'warning');
assert.equal(resultAppearance({...base,indices:[{indexCode:'XKTUM',isMember:true,period:'2020-01-01'}]}).variant,'warning');
console.log('PASS: green confirmed membership/compliance; red explicit non-compliance; yellow missing, conflicting, stale, future or unverified evidence.');
